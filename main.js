// ── Testimonials Infinite Loop ──
(function () {
  const wrap = document.getElementById('testiWrap');
  const track = document.getElementById('testiTrack');
  if (!wrap || !track) return;

  const CARDS_PER_SET = 8; // ← عدد بطاقاتك الحقيقي
  const CARD_WIDTH = 340;
  const GAP = 24;
  const SET_WIDTH = (CARD_WIDTH + GAP) * CARDS_PER_SET; // 2912px

  const COPIES = 4;
  track.innerHTML = track.innerHTML.repeat(COPIES);

  const SPEED = 0.6;
  let x = 0;
  let paused = false;

  let isDragging = false;
  let dragStartX = 0;
  let dragStartOffset = 0;

  wrap.addEventListener('mouseenter', () => {
    if (!isDragging) paused = true;
  });
  wrap.addEventListener('mouseleave', () => {
    if (!isDragging) paused = false;
  });

  function startDrag(clientX) {
    isDragging = true;
    paused = true;
    dragStartX = clientX;
    dragStartOffset = x;
    wrap.style.cursor = 'grabbing';
  }

  function updateDrag(clientX) {
    if (!isDragging) return;
    const delta = clientX - dragStartX;
    x = dragStartOffset + delta;
    if (Math.abs(x) >= SET_WIDTH) {
      x += Math.sign(x) * SET_WIDTH * -1;
    }
    track.style.transform = `translateX(${x}px)`;
  }

  function endDrag() {
    if (!isDragging) return;
    isDragging = false;
    paused = false;
    wrap.style.cursor = 'grab';
  }

  wrap.addEventListener('pointerdown', (event) => {
    if (event.pointerType === 'mouse' || event.pointerType === 'touch' || event.pointerType === 'pen') {
      wrap.setPointerCapture(event.pointerId);
      startDrag(event.clientX);
    }
  });

  wrap.addEventListener('pointermove', (event) => {
    if (!isDragging) return;
    updateDrag(event.clientX);
  });

  wrap.addEventListener('pointerup', (event) => {
    endDrag();
    wrap.releasePointerCapture(event.pointerId);
  });

  wrap.addEventListener('pointercancel', endDrag);

  function tick() {
    if (!paused) {
      x -= SPEED;
      if (Math.abs(x) >= SET_WIDTH) x += SET_WIDTH;
      track.style.transform = `translateX(${x}px)`;
    }
    requestAnimationFrame(tick);
  }

  requestAnimationFrame(() => requestAnimationFrame(tick));
})();

